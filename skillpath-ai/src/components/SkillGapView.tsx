import React, { useState } from 'react';
import {
  GitCompare,
  Sparkles,
  ArrowRight,
  TrendingUp,
  AlertTriangle,
  CheckCircle2,
  Clock,
  Filter,
  BarChart3,
  Award,
  Zap,
} from 'lucide-react';
import { SkillGapAnalysisResult, SkillGapItem, PrioritySkillToLearn } from '../types';

interface SkillGapViewProps {
  gapData: SkillGapAnalysisResult | null;
  careerName: string;
  onProceedToRoadmap: (weeklyHours?: string) => void;
}

export const SkillGapView: React.FC<SkillGapViewProps> = ({
  gapData,
  careerName,
  onProceedToRoadmap,
}) => {
  const [filterLevel, setFilterLevel] = useState<string>('all');
  const [weeklyHours, setWeeklyHours] = useState<string>('10–15 hours');

  if (!gapData) {
    return (
      <div className="text-center py-20 space-y-3">
        <p className="text-sm text-slate-400">Loading skill gap comparison...</p>
      </div>
    );
  }

  const safeSkillGaps = Array.isArray(gapData.skillGaps) ? gapData.skillGaps : [];
  const safeTopSkills = Array.isArray(gapData.topSkillsToLearn) ? gapData.topSkillsToLearn : [];
  const overallMatchScore = typeof gapData.overallMatchScore === 'number' ? gapData.overallMatchScore : 50;
  const readinessSummary = gapData.readinessSummary || 'Detailed readiness diagnostic generated by Gemini AI.';

  // Filter skills
  const filteredSkills = safeSkillGaps.filter((item) => {
    if (filterLevel === 'all') return true;
    return (item.status || '').toLowerCase() === filterLevel.toLowerCase();
  });

  // Calculate breakdown counts
  const counts = {
    strong: safeSkillGaps.filter((s) => s.status === 'Strong').length,
    intermediate: safeSkillGaps.filter((s) => s.status === 'Intermediate').length,
    beginner: safeSkillGaps.filter((s) => s.status === 'Beginner').length,
    missing: safeSkillGaps.filter((s) => s.status === 'Missing').length,
  };

  const getStatusBadge = (status: SkillGapItem['status']) => {
    switch (status) {
      case 'Strong':
        return (
          <span className="px-2.5 py-0.5 rounded-full text-xs font-bold bg-emerald-500/15 text-emerald-400 border border-emerald-500/30">
            Strong
          </span>
        );
      case 'Intermediate':
        return (
          <span className="px-2.5 py-0.5 rounded-full text-xs font-bold bg-indigo-500/15 text-indigo-400 border border-indigo-500/30">
            Intermediate
          </span>
        );
      case 'Beginner':
        return (
          <span className="px-2.5 py-0.5 rounded-full text-xs font-bold bg-amber-500/15 text-amber-400 border border-amber-500/30">
            Beginner
          </span>
        );
      case 'Missing':
      default:
        return (
          <span className="px-2.5 py-0.5 rounded-full text-xs font-bold bg-rose-500/15 text-rose-400 border border-rose-500/30">
            Missing
          </span>
        );
    }
  };

  const getScoreBarColor = (status: SkillGapItem['status']) => {
    switch (status) {
      case 'Strong':
        return 'bg-emerald-500';
      case 'Intermediate':
        return 'bg-indigo-500';
      case 'Beginner':
        return 'bg-amber-500';
      case 'Missing':
      default:
        return 'bg-rose-500';
    }
  };

  return (
    <div className="max-w-6xl mx-auto space-y-8 pb-16">
      {/* Header */}
      <div className="text-center space-y-3">
        <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-rose-500/10 border border-rose-500/25 text-xs font-semibold text-rose-300">
          <GitCompare className="w-3.5 h-3.5 text-rose-400" />
          <span>Stage 4: Automated Gap Diagnostics</span>
        </div>
        <h1 className="font-display text-3xl sm:text-4xl font-extrabold text-white tracking-tight">
          AI Skill Gap Analyzer
        </h1>
        <p className="text-xs sm:text-sm text-slate-300 max-w-2xl mx-auto">
          Comparing your verified resume credentials against industry expectations for{' '}
          <span className="text-rose-400 font-semibold">{careerName}</span>.
        </p>
      </div>

      {/* Top Summary Card with Match Gauge */}
      <div className="rounded-3xl border border-slate-800 bg-gradient-to-br from-slate-900 via-slate-900/90 to-slate-950 p-6 sm:p-8 grid grid-cols-1 lg:grid-cols-12 gap-6 items-center shadow-xl">
        <div className="lg:col-span-4 flex flex-col items-center justify-center p-4 bg-slate-950/60 rounded-2xl border border-slate-800/80">
          <div className="relative w-32 h-32 flex items-center justify-center">
            {/* SVG circular progress */}
            <svg className="w-full h-full transform -rotate-90" viewBox="0 0 36 36">
              <path
                className="text-slate-800"
                strokeWidth="3.5"
                stroke="currentColor"
                fill="none"
                d="M18 2.0845 a 15.9155 15.9155 0 0 1 0 31.831 a 15.9155 15.9155 0 0 1 0 -31.831"
              />
              <path
                className="text-indigo-500"
                strokeDasharray={`${overallMatchScore}, 100`}
                strokeWidth="3.5"
                strokeLinecap="round"
                stroke="currentColor"
                fill="none"
                d="M18 2.0845 a 15.9155 15.9155 0 0 1 0 31.831 a 15.9155 15.9155 0 0 1 0 -31.831"
              />
            </svg>
            <div className="absolute inset-0 flex flex-col items-center justify-center text-center">
              <span className="font-display text-3xl font-black text-white">
                {overallMatchScore}%
              </span>
              <span className="text-[10px] uppercase font-bold text-slate-400">Career Match</span>
            </div>
          </div>

          <div className="mt-4 text-center">
            <span className="text-xs font-bold text-indigo-300">
              {overallMatchScore > 75
                ? 'High Readiness'
                : overallMatchScore > 40
                ? 'Moderate Gap — Achievable with Focus'
                : 'Substantial Gap — Requires Foundation'}
            </span>
          </div>
        </div>

        <div className="lg:col-span-8 space-y-4">
          <div>
            <span className="text-[10px] uppercase font-bold text-slate-400">AI Readiness Diagnostic</span>
            <h3 className="font-display text-xl font-bold text-white mt-0.5">
              Readiness Assessment for {careerName}
            </h3>
          </div>

          <p className="text-xs sm:text-sm text-slate-300 leading-relaxed">
            {readinessSummary}
          </p>

          {/* Quick Metrics Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 pt-2">
            <div className="p-3 rounded-xl bg-emerald-950/20 border border-emerald-500/30 text-center">
              <span className="font-display text-xl font-bold text-emerald-400">{counts.strong}</span>
              <p className="text-[11px] text-slate-300 font-medium">Strong Skills</p>
            </div>
            <div className="p-3 rounded-xl bg-indigo-950/20 border border-indigo-500/30 text-center">
              <span className="font-display text-xl font-bold text-indigo-400">{counts.intermediate}</span>
              <p className="text-[11px] text-slate-300 font-medium">Intermediate</p>
            </div>
            <div className="p-3 rounded-xl bg-amber-950/20 border border-amber-500/30 text-center">
              <span className="font-display text-xl font-bold text-amber-400">{counts.beginner}</span>
              <p className="text-[11px] text-slate-300 font-medium">Beginner</p>
            </div>
            <div className="p-3 rounded-xl bg-rose-950/20 border border-rose-500/30 text-center">
              <span className="font-display text-xl font-bold text-rose-400">{counts.missing}</span>
              <p className="text-[11px] text-slate-300 font-medium">Missing Skills</p>
            </div>
          </div>
        </div>
      </div>

      {/* Top 5 Skills You Should Learn Next */}
      <div className="space-y-4">
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-2">
          <div>
            <div className="flex items-center gap-2 text-xs font-bold text-amber-400">
              <Zap className="w-4 h-4 fill-amber-400 text-amber-400" />
              <span>Prioritized Learning Sequence</span>
            </div>
            <h3 className="font-display text-xl font-bold text-white">
              Top 5 Skills You Should Learn Next
            </h3>
          </div>
          <span className="text-xs text-slate-400">
            Ranked based on prerequisites &amp; industry ROI
          </span>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
          {safeTopSkills.map((skill, idx) => (
            <div
              key={idx}
              className="rounded-2xl border border-slate-800 bg-slate-900/50 p-5 space-y-3 flex flex-col justify-between hover:border-indigo-500/40 hover:shadow-xl transition-all"
            >
              <div className="space-y-2">
                <div className="flex items-center justify-between">
                  <span className="font-display text-xs font-bold px-2 py-0.5 rounded bg-indigo-500/20 text-indigo-300 border border-indigo-500/30">
                    Priority #{idx + 1}
                  </span>
                  <span
                    className={`text-[10px] font-bold uppercase px-2 py-0.5 rounded ${
                      skill.priority === 'Urgent'
                        ? 'bg-rose-500/20 text-rose-400 border border-rose-500/30'
                        : 'bg-amber-500/20 text-amber-400 border border-amber-500/30'
                    }`}
                  >
                    {skill.priority}
                  </span>
                </div>

                <h4 className="font-display font-bold text-base text-white">
                  {skill.skill}
                </h4>

                <p className="text-xs text-slate-300 leading-relaxed">
                  <strong className="text-slate-200">Why you need it:</strong> {skill.whyYouNeedIt}
                </p>
              </div>

              <div className="space-y-2 pt-2 border-t border-slate-800/80 text-[11px]">
                <div className="flex items-center justify-between text-slate-400">
                  <span>Current Level:</span>
                  <span className="text-rose-300 font-semibold">{skill.currentLevel}</span>
                </div>
                <div className="flex items-center justify-between text-slate-400">
                  <span>Target Level:</span>
                  <span className="text-emerald-300 font-semibold">{skill.targetLevel}</span>
                </div>
                <div className="flex items-center justify-between text-slate-400">
                  <span className="flex items-center gap-1">
                    <Clock className="w-3 h-3 text-cyan-400" />
                    Est. Study:
                  </span>
                  <span className="text-cyan-300 font-semibold">{skill.estimatedHours} hrs</span>
                </div>
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Comprehensive Visual Skill-Gap Dashboard */}
      <div className="rounded-3xl border border-slate-800 bg-slate-900/40 p-6 sm:p-8 space-y-6">
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 border-b border-slate-800 pb-4">
          <div>
            <h3 className="font-display text-lg font-bold text-white flex items-center gap-2">
              <BarChart3 className="w-5 h-5 text-indigo-400" />
              <span>Comprehensive Skill-Gap Breakdown</span>
            </h3>
            <p className="text-xs text-slate-400">
              Direct comparison of every individual competency
            </p>
          </div>

          {/* Filter tabs */}
          <div className="flex flex-wrap items-center gap-1.5 bg-slate-950 p-1 rounded-xl border border-slate-800">
            {['all', 'strong', 'intermediate', 'beginner', 'missing'].map((level) => (
              <button
                key={level}
                onClick={() => setFilterLevel(level)}
                className={`px-3 py-1 rounded-lg text-xs font-semibold capitalize transition-all ${
                  filterLevel === level
                    ? 'bg-indigo-600 text-white shadow-sm'
                    : 'text-slate-400 hover:text-white hover:bg-slate-900'
                }`}
              >
                {level}
              </button>
            ))}
          </div>
        </div>

        {/* Skill comparison rows */}
        <div className="space-y-3">
          {filteredSkills.map((item, idx) => (
            <div
              key={idx}
              className="p-4 rounded-2xl bg-slate-950/70 border border-slate-800/80 space-y-2 hover:border-slate-700 transition-all"
            >
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                <div className="flex items-center gap-3">
                  <span className="text-xs font-bold text-white">{item.skill}</span>
                  <span className="text-[10px] px-2 py-0.5 rounded bg-slate-800 text-slate-400">
                    {item.category}
                  </span>
                  {item.importance === 'Critical' && (
                    <span className="text-[10px] font-bold text-rose-400 uppercase">
                      Critical
                    </span>
                  )}
                </div>

                <div className="flex items-center gap-3">
                  <span className="text-xs font-mono font-bold text-slate-200">
                    {item.score}%
                  </span>
                  {getStatusBadge(item.status)}
                </div>
              </div>

              {/* Progress Bar */}
              <div className="w-full h-2 bg-slate-800 rounded-full overflow-hidden">
                <div
                  className={`h-full rounded-full transition-all duration-500 ${getScoreBarColor(
                    item.status
                  )}`}
                  style={{ width: `${Math.max(item.score, 4)}%` }}
                />
              </div>

              {item.notes && (
                <p className="text-[11px] text-slate-400 italic pt-0.5">
                  Note: {item.notes}
                </p>
              )}
            </div>
          ))}
        </div>
      </div>

      {/* Bottom CTA Banner with Weekly Study Hours Selection */}
      <div className="p-6 rounded-3xl bg-gradient-to-r from-indigo-950 via-slate-900 to-cyan-950 border border-indigo-500/40 space-y-5 shadow-xl">
        <div className="flex flex-col md:flex-row items-start md:items-center justify-between gap-4">
          <div className="space-y-1">
            <h3 className="text-base font-bold text-white">
              Transform These Gaps into a Custom Step-by-Step Roadmap
            </h3>
            <p className="text-xs text-slate-300">
              Gemini AI organizes your missing skills into structured phases without repeating what you already know.
            </p>
          </div>

          <button
            id="generate-roadmap-btn"
            onClick={() => onProceedToRoadmap(weeklyHours)}
            className="flex items-center gap-2 px-6 py-3 rounded-xl font-bold text-sm text-white bg-gradient-to-r from-indigo-600 to-cyan-500 hover:from-indigo-500 hover:to-cyan-400 shadow-md shadow-indigo-600/30 active:scale-95 transition-all shrink-0"
          >
            <span>Generate Personalized Roadmap</span>
            <ArrowRight className="w-4 h-4" />
          </button>
        </div>

        {/* Weekly Hours Option Selector */}
        <div className="pt-4 border-t border-slate-800/80 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3">
          <span className="text-xs font-semibold text-slate-300 flex items-center gap-1.5">
            <Clock className="w-4 h-4 text-cyan-400" />
            How many hours can you learn per week?
          </span>
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 w-full sm:w-auto">
            {['3–5 hours', '5–10 hours', '10–15 hours', '15+ hours'].map((option) => (
              <button
                key={option}
                type="button"
                onClick={() => setWeeklyHours(option)}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                  weeklyHours === option
                    ? 'bg-cyan-500 text-slate-950 font-bold shadow-md shadow-cyan-500/30'
                    : 'bg-slate-800/80 text-slate-300 hover:bg-slate-700/80 hover:text-white border border-slate-700/60'
                }`}
              >
                {option}
              </button>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
};
